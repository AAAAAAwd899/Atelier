"""Generate legacy web and native palette adapters from the canonical role model."""
from pathlib import Path
import base64, json, argparse
ROOT=Path(__file__).resolve().parents[1]
WEB=ROOT/'src'/'web'
ROLE_KEYS={'canvas':'bg','sidebar':'side','panel':'panel','raised':'raised','input':'input',
 'selected':'accent-soft','border':'line-soft','strong-border':'line','text':'text',
 'muted':'muted','action':'accent','action-text':'on-accent','focus':'accent-strong',
 'success':'green','warning':'amber','error':'pink'}

def generate(check=False):
    contract=json.loads((WEB/'design-contract.json').read_text(encoding='utf8'))
    worlds=json.loads((WEB/'worlds.json').read_text(encoding='utf8'))
    palettes={}; sheets={name:[] for name in ['worlds-tokens.css','worlds-planner-tokens.css','worlds-review-tokens.css']}
    for w in worlds:
        name=w['id']; data=contract['worlds'][name]; roles=data['roles']
        p=dict(data['compatibility']); p.update({alias:roles[role] for role,alias in ROLE_KEYS.items()})
        palettes[name]=p
        common=''.join(f'--atelier-{k}:{v};' for k,v in roles.items())
        common+=''.join(f'--atelier-{k}:{v};' for k,v in contract['measurements'].items())
        aliases=''.join(f'--{k}:var(--atelier-{next(r for r,a in ROLE_KEYS.items() if a==k)});' if k in ROLE_KEYS.values() else f'--{k}:{v};' for k,v in p.items())
        scene='url("data:image/svg+xml;base64,'+base64.b64encode((WEB/w['art']).read_bytes()).decode()+'")'
        meta=f'--world-font:{w["font"]};--world-radius:{w["radius"]}px;'
        art=f'--world-art:{scene};--world-title:{json.dumps(w["title"])};'
        art+='--world-scene:'+('url("atelier-asset:'+w['scene']+'")' if w.get('scene') else 'var(--world-art)')+';'
        sheets['worlds-tokens.css'].append(f':host([data-theme="{name}"]),[data-world="{name}"],.mini-screen[data-theme="{name}"]{{{common}{aliases}{meta}{art}}}')
        sheets['worlds-planner-tokens.css'].append(f'html[data-atelier-world="{name}"]{{{common}{meta}{art}}}')
        sheets['worlds-review-tokens.css'].append(f'html[data-atelier-world="{name}"]{{{common}{meta}}}')
    outputs={WEB/'palettes.json':json.dumps(palettes,indent=2)+'\n'}
    outputs.update({WEB/name:'/* Generated by tools/generate_design.py. Edit design-contract.json or worlds.json. */\n'+'\n'.join(lines)+'\n' for name,lines in sheets.items()})
    for path,text in outputs.items():
        if check:
            if path.read_text(encoding='utf8')!=text:raise SystemExit('Stale generated adapter: '+path.name)
        else:path.write_text(text,encoding='utf8')
    print('Canonical roles: 12 worlds; home, planner, reviewer and native palette adapters verified.')
if __name__=='__main__':
    parser=argparse.ArgumentParser();parser.add_argument('--check',action='store_true');generate(parser.parse_args().check)
